#!/usr/bin/env python3
"""Write themes/opal.yaml from src/theme.template.yaml and src/variants.yaml.

Every variant fills the ${...} fields of the template; the themes follow each other in
one file, the order of src/variants.yaml. With --check nothing is written: the script
fails when themes/opal.yaml is not what it would write (used by the Validate workflow).

Needs PyYAML. Usage: script/build.py [--check]
"""

import string
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "src" / "theme.template.yaml"
VARIANTS = ROOT / "src" / "variants.yaml"
OUTPUT = ROOT / "themes" / "opal.yaml"

HEADER = """\
---
# Opal: a Home Assistant theme with frosted-glass cards (backdrop blur) over soft
# coloured light, in a light and a dark mode, and its gemstone variants.
# https://github.com/tb1337/home-assistant-opal-theme
#
# Generated by script/build.py from src/theme.template.yaml and src/variants.yaml:
# change those and run the script, not this file.
#
# Select a theme in your profile ("Opal" or a variant), then Auto, Light or Dark.
# Anything not set here comes from Home Assistant's own light or dark palette.
# The card-mod-* keys need card-mod (thomasloven/lovelace-card-mod); without it they are
# ignored and the theme still works.
"""


def template_body() -> string.Template:
    """The template from its first theme line on, without its own header."""
    lines = TEMPLATE.read_text(encoding="utf-8").splitlines(keepends=True)
    start = next(i for i, line in enumerate(lines) if line.startswith("${name}:"))
    return string.Template("".join(lines[start:]))


def fields(variant: dict) -> dict:
    """The template's fields for one variant."""
    out = {"name": variant["name"], "slug": variant["slug"]}
    out.update({f"p{step}": value for step, value in variant["palette"].items()})
    out.update({f"l_{key}": value for key, value in variant["light"].items()})
    out.update({f"d_{key}": value for key, value in variant["dark"].items()})
    return out


def build() -> str:
    body = template_body()
    variants = yaml.safe_load(VARIANTS.read_text(encoding="utf-8"))
    themes = [body.substitute(fields(variant)) for variant in variants]
    text = HEADER + "\n" + "\n".join(themes)
    # The result must be valid YAML with one theme per variant.
    loaded = yaml.safe_load(text)
    names = [variant["name"] for variant in variants]
    if list(loaded) != names:
        raise SystemExit(f"built themes {list(loaded)} do not match the variants {names}")
    return text


def main() -> int:
    text = build()
    if "--check" in sys.argv[1:]:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run script/build.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
